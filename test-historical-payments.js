const assert = require('assert/strict');
const vm = require('vm');
const fs = require('fs');
const saved = new Map();
const context = {window:null,localStorage:{getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v)},Date,console};
context.window=context;
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname, 'store.js'),'utf8'),context);
const s=context.PGStore;
s.use('historical-test');
const current=s.monthKey();
const before=new Date(current+'-01T00:00:00Z');before.setUTCMonth(before.getUTCMonth()-1);
const prior=before.toISOString().slice(0,7);
const old=new Date(current+'-01T00:00:00Z');old.setUTCMonth(old.getUTCMonth()-2);
const older=old.toISOString().slice(0,7);
s.addRoom({no:'101',floor:0,beds:2,rent:6000});
const room=s.state().rooms[0];
s.addTenant(room.id,0,{name:'Tenant',joined:older+'-01'});
assert.equal(s.updateMonthPayment(room.id,0,prior,{rent:5500,paid:true,paymentDate:prior+'-05',utr:'OLD'}).ok,true);
assert.equal(s.updateMonthPayment(room.id,0,prior,{rent:5250,paid:true,paymentDate:prior+'-12',utr:'FIXED'}).ok,true);
let record=s.ledger(room.id,0).find(m=>m.month===prior);
assert.equal(record.rent,5250);assert.equal(record.paymentDate,prior+'-12');assert.equal(record.utr,'FIXED');assert.equal(record.paid,true);
assert.equal(room.beds[0].paid,false,'editing previous month cannot mark current month paid');
let snap=JSON.stringify(s.state());
for(const patch of [{rent:-1,paid:true},{rent:NaN,paid:true},{rent:5000,paid:true,paymentDate:'2026-02-30'}]) {
 assert.equal(s.updateMonthPayment(room.id,0,prior,patch).ok,false);assert.equal(JSON.stringify(s.state()),snap);
}
s.updateRoom(room.id,{rent:7000});
assert.equal(s.monthRent(room,room.beds[0],older),6000,'old unpaid rent preserved');
assert.equal(s.monthRent(room,room.beds[0],prior),5250,'explicit old paid rent preserved');
assert.equal(s.monthRent(room,room.beds[0],current),7000,'unsettled current month uses new rent');
assert.equal(s.outstanding().amount,13000);
s.setPaid(room.id,0,true,current+'-10','CURRENT');
s.updateRoom(room.id,{rent:8000});
assert.equal(s.monthRent(room,room.beds[0],current),7000,'settled current rent preserved');
s.updateMonthPayment(room.id,0,prior,{rent:5250,paid:false});
assert.equal(s.monthRent(room,room.beds[0],prior),5250,'undo preserves edited monthly amount');
assert.equal(s.outstanding().amount,11250);
s.updateMonthPayment(room.id,0,'2001-01',{rent:0,paid:true,paymentDate:'2001-01-05',utr:'HISTORIC'});
assert.equal(s.ledger(room.id,0).find(m=>m.month==='2001-01').rent,0);
s.use('historical-test');
const fresh=s.state().rooms[0];
assert.equal(s.monthRent(fresh,fresh.beds[0],prior),5250);
assert.equal(s.ledger(fresh.id,0).find(m=>m.month==='2001-01').utr,'HISTORIC');
s.use('other-owner');assert.equal(s.state().rooms.length,0);
console.log('Historical monthly amounts, corrections, validation, undo, rate changes, persistence and account isolation passed.');
